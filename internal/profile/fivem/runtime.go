package fivem

import (
	"bytes"
	"errors"
	"fmt"
	"sort"
	"strings"

	"fxvcs.dev/fxvcs/internal/domain"
	"fxvcs.dev/fxvcs/internal/profile/fivem/discovery"
)

var ErrRuntimeConfig = errors.New("fivem: invalid generated runtime config")

var txAdminOwnedResources = map[string]bool{
	"monitor":       true,
	"txadmin":       true,
	"txadminclient": true,
}

// RuntimeConfig renders the FXVCS-owned portion of runtime/fxvcs.cfg. It is
// deliberately limited to the immutable Release activation plan; typed cfg
// fragments are rendered separately and may be passed as realization-relative
// paths beneath runtime/config once their hooks have completed.
func RuntimeConfig(resources []domain.ReleaseResource, fragments []string) ([]byte, error) {
	return RuntimeConfigWithHealth(resources, fragments, false)
}

// RuntimeConfigWithHealth appends the built-in authenticated health resource
// after every release resource so its report observes the final start order.
func RuntimeConfigWithHealth(resources []domain.ReleaseResource, fragments []string, includeHealth bool) ([]byte, error) {
	ordered := append([]domain.ReleaseResource(nil), resources...)
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].EnsureOrder != ordered[j].EnsureOrder {
			return ordered[i].EnsureOrder < ordered[j].EnsureOrder
		}
		return ordered[i].Name < ordered[j].Name
	})

	seenNames := map[string]bool{}
	seenOrders := map[int]string{}
	var enabled []string
	for _, resource := range ordered {
		if resource.Activation != domain.ActivationEnabled && resource.Activation != domain.ActivationDisabled {
			return nil, fmt.Errorf("%w: resource %q has activation %q", ErrRuntimeConfig, resource.Name, resource.Activation)
		}
		key := strings.ToLower(resource.Name)
		if seenNames[key] {
			return nil, fmt.Errorf("%w: duplicate resource name %q", ErrRuntimeConfig, resource.Name)
		}
		seenNames[key] = true
		if previous, ok := seenOrders[resource.EnsureOrder]; ok {
			return nil, fmt.Errorf("%w: resources %q and %q share ensure order %d", ErrRuntimeConfig, previous, resource.Name, resource.EnsureOrder)
		}
		seenOrders[resource.EnsureOrder] = resource.Name
		if resource.Activation == domain.ActivationDisabled {
			continue
		}
		if resource.Source == domain.ResourceSourceRuntime || resource.Source == domain.ResourceSourceExternal {
			// Target-provided runtime resources and externally owned resources
			// are verified as host evidence and never started by generated cfg.
			continue
		}
		if err := discovery.ValidateResourceName(resource.Name); err != nil {
			return nil, fmt.Errorf("%w: %v", ErrRuntimeConfig, err)
		}
		if txAdminOwnedResources[key] {
			return nil, fmt.Errorf("%w: resource %q is owned by txAdmin and cannot be ensured by fxvcs", ErrRuntimeConfig, resource.Name)
		}
		enabled = append(enabled, resource.Name)
	}
	if includeHealth && seenNames[HealthResourceName] {
		return nil, fmt.Errorf("%w: release resource %q collides with the built-in health resource", ErrRuntimeConfig, HealthResourceName)
	}

	fragmentCopy := append([]string(nil), fragments...)
	sort.Strings(fragmentCopy)
	seenFragments := map[string]bool{}
	var b bytes.Buffer
	b.WriteString("# Generated by fxvcs; do not edit.\n")
	for _, fragment := range fragmentCopy {
		if !strings.HasPrefix(fragment, "runtime/config/") || strings.ContainsAny(fragment, "\\\x00\r\n") {
			return nil, fmt.Errorf("%w: fragment %q is outside runtime/config", ErrRuntimeConfig, fragment)
		}
		relative := strings.TrimPrefix(fragment, "runtime/")
		if relative == "config/" || strings.Contains(relative, "//") || strings.Contains(relative, "/../") || strings.HasSuffix(relative, "/..") || strings.Contains(relative, "/./") {
			return nil, fmt.Errorf("%w: fragment %q is not normalized", ErrRuntimeConfig, fragment)
		}
		if seenFragments[relative] {
			return nil, fmt.Errorf("%w: duplicate fragment %q", ErrRuntimeConfig, fragment)
		}
		seenFragments[relative] = true
		b.WriteString("exec ")
		b.WriteString(relative)
		b.WriteByte('\n')
	}
	if len(fragmentCopy) > 0 && len(enabled) > 0 {
		b.WriteByte('\n')
	}
	for _, name := range enabled {
		b.WriteString("ensure ")
		b.WriteString(name)
		b.WriteByte('\n')
	}
	if includeHealth {
		b.WriteString("ensure ")
		b.WriteString(HealthResourceName)
		b.WriteByte('\n')
	}
	return b.Bytes(), nil
}
