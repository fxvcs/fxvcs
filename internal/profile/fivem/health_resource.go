package fivem

import (
	"bytes"
	"encoding/json"
	"fmt"
	"sort"
	"strings"

	"fxvcs.dev/fxvcs/internal/domain"
	"fxvcs.dev/fxvcs/internal/profile/fivem/discovery"
)

const (
	HealthResourceName       = "fxvcs-health"
	HealthResourceConfigPath = "runtime/config/fxvcs-health.cfg"
	HealthResourceRoot       = "resources/[fxvcs]/fxvcs-health"
)

type GeneratedHealthFile struct {
	Path string
	Data []byte
}

// ResourceStateFiles returns the deterministic built-in FiveM resource used by
// the optional authenticated readiness check. The token is read only from a
// non-replicated server convar and is never embedded in these files.
func ResourceStateFiles(resources []domain.ReleaseResource) ([]GeneratedHealthFile, error) {
	ordered := append([]domain.ReleaseResource(nil), resources...)
	sort.Slice(ordered, func(i, j int) bool {
		if ordered[i].EnsureOrder != ordered[j].EnsureOrder {
			return ordered[i].EnsureOrder < ordered[j].EnsureOrder
		}
		return ordered[i].Name < ordered[j].Name
	})
	names := make([]string, 0, len(ordered))
	seen := map[string]bool{}
	for _, resource := range ordered {
		if resource.Activation != domain.ActivationEnabled {
			continue
		}
		if err := discovery.ValidateResourceName(resource.Name); err != nil {
			return nil, fmt.Errorf("%w: health resource expected name: %v", ErrRuntimeConfig, err)
		}
		key := strings.ToLower(resource.Name)
		if key == HealthResourceName {
			return nil, fmt.Errorf("%w: release resource %q collides with the built-in health resource", ErrRuntimeConfig, resource.Name)
		}
		if seen[key] {
			return nil, fmt.Errorf("%w: duplicate expected resource %q", ErrRuntimeConfig, resource.Name)
		}
		seen[key] = true
		names = append(names, resource.Name)
	}
	expected, err := json.Marshal(names)
	if err != nil {
		return nil, err
	}
	manifest := []byte("fx_version 'cerulean'\ngame 'gta5'\nserver_only 'yes'\nserver_script 'server.lua'\n")
	var server bytes.Buffer
	server.WriteString("-- Generated by fxvcs; do not edit.\n")
	server.WriteString("local expected = json.decode([[")
	server.Write(expected)
	server.WriteString("]])\n")
	server.WriteString(`local function isLoopback(address)
    if address == '127.0.0.1' or address == '::1' then return true end
    if string.match(address or '', '^127%.0%.0%.1:') then return true end
    if string.match(address or '', '^%[::1%]:') then return true end
    return false
end

SetHttpHandler(function(request, response)
    if request.method ~= 'GET' or request.path ~= '/state' then
        response.writeHead(404, { ['Content-Type'] = 'application/json', ['Cache-Control'] = 'no-store' })
        return response.send(json.encode({ error = 'not found' }))
    end
    if not isLoopback(request.address) then
        response.writeHead(403, { ['Content-Type'] = 'application/json', ['Cache-Control'] = 'no-store' })
        return response.send(json.encode({ error = 'forbidden' }))
    end
    local token = GetConvar('fxvcs_health_token', '')
    local supplied = request.headers['authorization'] or request.headers['Authorization'] or ''
    if token == '' or supplied ~= ('Bearer ' .. token) then
        response.writeHead(403, { ['Content-Type'] = 'application/json', ['Cache-Control'] = 'no-store' })
        return response.send(json.encode({ error = 'forbidden' }))
    end
    local healthy = true
    local states = {}
    for _, name in ipairs(expected) do
        local state = GetResourceState(name)
        states[#states + 1] = { name = name, state = state }
        if state ~= 'started' then healthy = false end
    end
    response.writeHead(200, { ['Content-Type'] = 'application/json', ['Cache-Control'] = 'no-store' })
    return response.send(json.encode({ healthy = healthy, resources = states }))
end)
`)
	return []GeneratedHealthFile{
		{Path: HealthResourceRoot + "/fxmanifest.lua", Data: manifest},
		{Path: HealthResourceRoot + "/server.lua", Data: server.Bytes()},
	}, nil
}

// ResourceStateConfig renders the credential through the same strict cfg
// quoting rules as secret-bearing template outputs.
func ResourceStateConfig(token []byte) ([]byte, error) {
	if len(token) < 16 || len(token) > 512 {
		return nil, fmt.Errorf("%w: health token is missing or invalid", ErrRuntimeConfig)
	}
	for _, char := range token {
		if char < 0x20 || char == 0x7f {
			return nil, fmt.Errorf("%w: health token is missing or invalid", ErrRuntimeConfig)
		}
	}
	escaped := strings.ReplaceAll(string(token), `\`, `\\`)
	escaped = strings.ReplaceAll(escaped, `"`, `\"`)
	return []byte("set fxvcs_health_token \"" + escaped + "\"\n"), nil
}
