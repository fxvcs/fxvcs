package fivem

import (
	"errors"
	"testing"

	"fxvcs.dev/fxvcs/internal/domain"
)

func TestRuntimeConfigDeterministicActivationOrder(t *testing.T) {
	resources := []domain.ReleaseResource{
		{Name: "disabled", Activation: domain.ActivationDisabled, EnsureOrder: 2},
		{Name: "inventory", Activation: domain.ActivationEnabled, EnsureOrder: 1},
		{Name: "mapmanager", Activation: domain.ActivationEnabled, EnsureOrder: 0},
	}
	got, err := RuntimeConfig(resources, []string{"runtime/config/z.cfg", "runtime/config/a.cfg"})
	if err != nil {
		t.Fatal(err)
	}
	want := "# Generated by fxvcs; do not edit.\nexec config/a.cfg\nexec config/z.cfg\n\nensure mapmanager\nensure inventory\n"
	if string(got) != want {
		t.Fatalf("got:\n%s\nwant:\n%s", got, want)
	}
}

func TestRuntimeConfigRefusesAmbiguousOrOwnedResources(t *testing.T) {
	cases := [][]domain.ReleaseResource{
		{{Name: "monitor", Activation: domain.ActivationEnabled, EnsureOrder: 0}},
		{{Name: "chat", Activation: domain.ActivationEnabled, EnsureOrder: 0}, {Name: "CHAT", Activation: domain.ActivationDisabled, EnsureOrder: 1}},
		{{Name: "chat", Activation: domain.ActivationEnabled, EnsureOrder: 0}, {Name: "mapmanager", Activation: domain.ActivationEnabled, EnsureOrder: 0}},
		{{Name: "bad name", Activation: domain.ActivationEnabled, EnsureOrder: 0}},
	}
	for _, resources := range cases {
		if _, err := RuntimeConfig(resources, nil); !errors.Is(err, ErrRuntimeConfig) {
			t.Fatalf("resources %+v: got %v", resources, err)
		}
	}
	if _, err := RuntimeConfig(nil, []string{"resources/secret.cfg"}); !errors.Is(err, ErrRuntimeConfig) {
		t.Fatalf("unsafe fragment accepted: %v", err)
	}
}

func TestRuntimeConfigOmitsHostOwnedResources(t *testing.T) {
	got, err := RuntimeConfig([]domain.ReleaseResource{
		{Name: "chat", Source: domain.ResourceSourceComponent, Activation: domain.ActivationEnabled, EnsureOrder: 0},
		{Name: "monitor", Source: domain.ResourceSourceRuntime, Activation: domain.ActivationEnabled, EnsureOrder: 1},
		{Name: "custom-anticheat", Source: domain.ResourceSourceExternal, Activation: domain.ActivationEnabled, EnsureOrder: 2},
	}, nil)
	if err != nil {
		t.Fatal(err)
	}
	if string(got) != "# Generated by fxvcs; do not edit.\nensure chat\n" {
		t.Fatalf("host-owned resource was emitted:\n%s", got)
	}
}
